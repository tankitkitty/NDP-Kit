import { ReportParam } from "../types";

/**
 * รายงานที่ติดมากับตัวโปรแกรม
 *
 * เขียนไว้ในโค้ด ไม่ได้เก็บในไฟล์ข้อมูลของเครื่อง หน่วยบริการจึงได้รายงานชุดนี้
 * เหมือนกันทุกที่ทันทีที่อัปเดตเวอร์ชัน ไม่ต้องกดดึงและไม่ต้องนำเข้าไฟล์
 *
 * ไม่มี createdAt/updatedAt/source/author เพราะเป็นของที่มากับโปรแกรม
 * ไม่ใช่ของที่ใครคนใดคนหนึ่งในเครื่องนั้นสร้าง — ตัวประกอบใน index.ts เติมให้เอง
 */
export interface BuiltinReport {
  /**
   * รหัสสั้นๆ ที่ไม่ซ้ำกัน เช่น "daily-visits"
   *
   * ห้ามเปลี่ยนหลังปล่อยไปแล้ว เพราะ URL ของหน้ารายงาน (/reports/builtin:xxx)
   * ผูกกับค่านี้ ถ้าเปลี่ยนลิงก์ที่ผู้ใช้บุ๊กมาร์กไว้จะเปิดไม่ได้
   */
  id: string;
  name: string;
  group: string;
  description: string;
  /** คำสั่ง SELECT อ้างพารามิเตอร์ด้วย :ชื่อ เหมือนรายงานที่ผู้ใช้เขียนเอง */
  sql: string;
  params: ReportParam[];
}
